/// The faint geometric pattern behind the screens on supporter themes (≈ ThemeHelper on Android).
///
/// The shape is the Android vector (bg_khatam_star) drawn as hexagon tiles: one in the middle of
/// each tile plus the four corners, at 5–6/255 opacity (white on dark colors, black on light ones).
/// The tile is drawn once per base color and cached, exactly like the Android bitmap cache.
enum KhatamPattern {
    private static let hexagonWidth: CGFloat = 72
    private static var cache: [ARGB: UIImage] = [:]

    /// A tile to repeat over `base`.
    static func tile(base: ARGB) -> UIImage {
        if let cached = cache[base] { return cached }
        let width = (hexagonWidth * 1.5).rounded()
        let hexWidth = width / 1.5
        let height = (hexWidth * 0.8660254).rounded()
        let size = CGSize(width: width, height: height)

        let format = UIGraphicsImageRendererFormat()
        format.opaque = true
        let image = UIGraphicsImageRenderer(size: size, format: format).image { context in
            let cg = context.cgContext
            UIColor(Color(argb: base)).setFill()
            cg.fill(CGRect(origin: .zero, size: size))

            let light = ColorMath.isLight(base)
            let stroke = light ? UIColor(white: 0, alpha: 6 / 255) : UIColor(white: 1, alpha: 5 / 255)
            let scaleX = hexWidth / viewport.width
            let scaleY = height / viewport.height
            let centers = [CGPoint(x: width / 2, y: height / 2), CGPoint(x: 0, y: 0), CGPoint(x: width, y: 0),
                           CGPoint(x: 0, y: height), CGPoint(x: width, y: height)]
            for center in centers {
                var transform = CGAffineTransform(translationX: center.x - hexWidth / 2, y: center.y - height / 2)
                    .scaledBy(x: scaleX, y: scaleY)
                guard let path = shape.copy(using: &transform) else { continue }
                cg.addPath(path)
                cg.setStrokeColor(stroke.cgColor)
                cg.setLineWidth(2 * scaleX)
                cg.setLineJoin(.miter)
                cg.strokePath()
            }
        }
        cache[base] = image
        return image
    }

    // MARK: Shape (copied from the Android vector drawable)

    private static let viewport = CGSize(width: 172.91, height: 149.48)

    /// The path in viewport coordinates, with the vector's group transforms applied:
    /// rotate 90° around (90.11, 89.455), then translate by (-3.655, -14.715).
    static let shape: CGPath = {
        let path = parse(pathData)
        var rotation = CGAffineTransform(translationX: 90.11, y: 89.455)
            .rotated(by: .pi / 2)
            .translatedBy(x: -90.11, y: -89.455)
        let rotated = path.copy(using: &rotation) ?? path
        var shift = CGAffineTransform(translationX: -3.655, y: -14.715)
        return rotated.copy(using: &shift) ?? rotated
    }()

    /// Parses the subset of SVG path syntax the vector uses: absolute M, L and Z.
    static func parse(_ data: String) -> CGPath {
        let path = CGMutablePath()
        var command: Character = "M"
        var numbers: [CGFloat] = []
        var token = ""

        func endToken() {
            if let value = Double(token) { numbers.append(CGFloat(value)) }
            token = ""
            if numbers.count == 2 {
                let point = CGPoint(x: numbers[0], y: numbers[1])
                if command == "M" {
                    path.move(to: point)
                    command = "L"  // extra coordinate pairs after M are lines (SVG rule)
                } else {
                    path.addLine(to: point)
                }
                numbers.removeAll()
            }
        }

        for character in data {
            switch character {
            case "M", "L":
                endToken()
                command = character
            case "Z":
                endToken()
                path.closeSubpath()
            case ",", " ", "\n":
                endToken()
            default:
                token.append(character)
            }
        }
        endToken()
        return path
    }

